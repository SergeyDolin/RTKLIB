def copy_rpr(paragraph):
    for run in paragraph.runs:
        if run._r.rPr is not None:
            return deepcopy(run._r.rPr)
    return None


def clear_text(paragraph):
    for child in list(paragraph._p):
        if child.tag in {qn("w:r"), qn("w:hyperlink")}:
            paragraph._p.remove(child)


def add_run(paragraph, text, rpr, bold=None):
    run = paragraph.add_run(text)
    if rpr is not None:
        if run._r.rPr is not None:
            run._r.remove(run._r.rPr)
        run._r.insert(0, deepcopy(rpr))
    if bold is not None:
        run.bold = bold


def set_plain(paragraph, text):
    rpr = copy_rpr(paragraph)
    clear_text(paragraph)
    add_run(paragraph, text, rpr)


def set_labeled(paragraph, label, body):
    rpr = copy_rpr(paragraph)
    clear_text(paragraph)
    add_run(paragraph, label, rpr, bold=True)
    add_run(paragraph, body, rpr, bold=False)


def paragraph_after_heading(document, heading, offset=1):
    index = next(i for i, p in enumerate(document.paragraphs) if p.text.strip() == heading)
    return document.paragraphs[index + offset]


def main():
    document = Document(SOURCE)

    set_plain(paragraph_after_heading(document, "Научная и профессиональная деятельность", 1), ACTIVITY_SUMMARY)

    for offset, text in enumerate(MAIN_RESULTS, start=1):
        set_plain(paragraph_after_heading(document, "Основные научные результаты", offset), text)

    for prefix, content in PERSONAL_BLOCKS.items():
        paragraph = next(p for p in document.paragraphs if p.text.startswith(prefix))
        set_labeled(paragraph, *content)
        paragraph.paragraph_format.keep_together = True

    dissertation = paragraph_after_heading(document, "Экспериментальные показатели", 1)
    mobile = paragraph_after_heading(document, "Экспериментальные показатели", 2)
    set_labeled(dissertation, *EXPERIMENT_BLOCKS[0])
    set_labeled(mobile, *EXPERIMENT_BLOCKS[2])
    dissertation.paragraph_format.keep_together = True
    mobile.paragraph_format.keep_together = True

    new_xml = deepcopy(dissertation._p)
    dissertation._p.addnext(new_xml)
    new_paragraph = Paragraph(new_xml, dissertation._parent)
    set_labeled(new_paragraph, *EXPERIMENT_BLOCKS[1])
    new_paragraph.paragraph_format.keep_together = True

    document.save(OUTPUT)


if __name__ == "__main__":
    main()
